const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('pet', {
  onState: (fn) => ipcRenderer.on('state', (_e, s) => fn(s)),
  onReward: (fn) => ipcRenderer.on('reward', (_e, r) => fn(r)),
  openPlay: (game) => ipcRenderer.send('open-play', game),
  onAction: (fn) => ipcRenderer.on('action', (_e, a) => fn(a)),
  mouseOverPet: (over) => ipcRenderer.send('mouse-over-pet', over),
  dragStart: () => ipcRenderer.send('drag-start'),
  dragMove: () => ipcRenderer.send('drag-move'),
  dragEnd: () => ipcRenderer.send('drag-end'),
  moveTo: (x, y) => ipcRenderer.send('move-to', x, y),
  moveBy: (dx, dy) => ipcRenderer.send('move-by', dx, dy),
  getBounds: () => ipcRenderer.invoke('get-bounds'),
  getCursor: () => ipcRenderer.invoke('get-cursor'),
  dragDone: () => ipcRenderer.send('drag-done'),
  contextMenu: () => ipcRenderer.send('context-menu'),
  focus: () => ipcRenderer.send('focus-pet'),
  glideCenter: () => ipcRenderer.send('glide-center'),
  glideHome: () => ipcRenderer.send('glide-home'),
  save: (partial) => ipcRenderer.send('save-state', partial),
  track: (event, n) => ipcRenderer.send('track', event, n),
  insight: (kind, value) => ipcRenderer.send('insight', kind, value),
  onAchievement: (fn) => ipcRenderer.on('achievement', (_e, id) => fn(id)),
  onQuiet: (fn) => ipcRenderer.on('quiet', (_e, q) => fn(q)),
  onActivity: (fn) => ipcRenderer.on('activity', (_e, idleSec) => fn(idleSec)),
  onCompany: (fn) => ipcRenderer.on('company', (_e, m) => fn(m)),
  companyShown: (kind, id, shown) => ipcRenderer.send('company-shown', kind, id, shown),
  openTeams: () => ipcRenderer.send('open-teams'),
  companyAnswer: (id, a) => ipcRenderer.send('company-answer', id, a),
});
